from fpdf import FPDF
import re
import os
from datetime import datetime

FONT_DIR = os.path.join(os.path.dirname(__file__), "fonts")
FONT_REGULAR = os.path.join(FONT_DIR, "NotoSans-Regular.ttf")
FONT_BOLD = os.path.join(FONT_DIR, "NotoSans-Bold.ttf")

def clean_text(text: str) -> str:
    text = re.sub(r'\*\*(.*?)\*\*', r'\1', text)
    text = re.sub(r'\*(.*?)\*', r'\1', text)
    text = re.sub(r'#{1,6}\s*(.*)', r'\1', text)
    text = re.sub(r'`(.*?)`', r'\1', text)
    return text.strip()

class SpaceIntelPDF(FPDF):
    def header(self):
        pass

    def footer(self):
        self.set_y(-15)
        self.set_font("NotoSans", "", 9)
        self.set_text_color(100, 100, 120)
        self.cell(0, 10, "Generated by SpaceIntel · AI Knowledge Assistant for Space Research", align="C")

def generate_chat_report(messages: list, title: str = "SpaceIntel Research Report") -> bytes:
    pdf = SpaceIntelPDF()
    pdf.add_page()
    pdf.set_margins(20, 20, 20)
    pdf.set_auto_page_break(auto=True, margin=25)

    # Add Unicode fonts
    pdf.add_font("NotoSans", "", FONT_REGULAR)
    pdf.add_font("NotoSans", "B", FONT_BOLD)

    # Header background
    pdf.set_fill_color(4, 8, 15)
    pdf.rect(0, 0, 210, 42, "F")
    pdf.set_y(10)
    pdf.set_font("NotoSans", "B", 22)
    pdf.set_text_color(0, 212, 255)
    pdf.cell(0, 12, "SPACEINTEL", align="C", ln=True)
    pdf.set_font("NotoSans", "", 9)
    pdf.set_text_color(0, 150, 180)
    pdf.cell(0, 6, "AI-POWERED SPACE RESEARCH ASSISTANT", align="C", ln=True)
    pdf.set_font("NotoSans", "", 8)
    pdf.set_text_color(100, 100, 130)
    pdf.cell(0, 6, f"Generated: {datetime.now().strftime('%B %d, %Y at %H:%M')}", align="C", ln=True)

    pdf.set_y(47)
    pdf.set_draw_color(0, 212, 255)
    pdf.set_line_width(0.3)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(6)

    # Filter Q&A pairs
    qa_pairs = []
    i = 0
    while i < len(messages):
        if messages[i]['role'] == 'user':
            question = messages[i]['content']
            answer = ""
            sources = []
            if i + 1 < len(messages) and messages[i+1]['role'] == 'bot':
                answer = messages[i+1]['content']
                sources = messages[i+1].get('sources', [])
                i += 2
            else:
                i += 1
            qa_pairs.append((question, answer, sources))
        else:
            i += 1

    for idx, (question, answer, sources) in enumerate(qa_pairs):
        # Question
        pdf.set_font("NotoSans", "B", 11)
        pdf.set_text_color(0, 100, 160)
        q_text = f"Q{idx+1}. {clean_text(question)}"
        pdf.multi_cell(170, 7, q_text)
        pdf.ln(2)

        # Answer - split by paragraphs
        pdf.set_font("NotoSans", "", 10)
        pdf.set_text_color(20, 20, 40)
        answer_clean = clean_text(answer)
        for para in answer_clean.split('\n'):
            para = para.strip()
            if para and len(para) > 1:
                pdf.multi_cell(170, 6, para)
        pdf.ln(2)

        # Sources - page numbers only, no long text
        clean_sources = [s for s in sources if s.get('filename', '') != 'unknown.pdf']
        if clean_sources:
            pdf.set_font("NotoSans", "B", 9)
            pdf.set_text_color(100, 70, 170)
            pdf.cell(170, 5, "SOURCES:", ln=True)
            pdf.set_font("NotoSans", "", 9)
            pdf.set_text_color(80, 80, 110)
            for src in clean_sources[:3]:
                filename = str(src.get('filename', ''))[:50]
                page = src.get('page_number', '?')
                src_text = f"Page {page} - {filename}"
                pdf.cell(170, 5, src_text, ln=True)

        pdf.ln(3)
        pdf.set_draw_color(220, 220, 235)
        pdf.set_line_width(0.2)
        pdf.line(20, pdf.get_y(), 190, pdf.get_y())
        pdf.ln(4)

    return bytes(pdf.output())